local ORIGINAL = "original"
local ORIGINAL_V2 = "originalV2"
local MINI = "mini"
local XL = "xl"
local XL_V2 = "xlV2"
local MK2 = "mk2"
local MK2_SCISSOR = "mk2Scissor"
local MINI_MK2 = "miniMk2"
local NEO = "neo"
local PEDAL = "pedal"
local PLUS = "plus"

local info = {
    ORIGINAL = ORIGINAL,
    ORIGINAL_V2 = ORIGINAL_V2,
    MINI = MINI,
    XL = XL,
    XL_V2 = XL_V2,
    MK2 = MK2,
    MK2_SCISSOR = MK2_SCISSOR,
    MINI_MK2 = MINI_MK2,
    NEO = NEO,
    PEDAL = PEDAL,
    PLUS = PLUS
}

info.elgatoVID = 0xFD9

local kindToPID = {
    [ ORIGINAL ] = 0x60,
    [ ORIGINAL_V2 ] = 0x6d,
    [ MINI ] = 0x63,
    [ XL ] = 0x6c,
    [ XL_V2 ] = 0x8f,
    [ MK2 ] = 0x80,
    [ MK2_SCISSOR ] = 0xa5,
    [ MINI_MK2 ] = 0x90,
    [ NEO ] = 0x9a,
    [ PEDAL ] = 0x86,
    [ PLUS ] = 0x84
}

local pidToKind = {}
for k, v in pairs(kindToPID) do pidToKind[v] = k end

---Checks if the PID is one of the stream decks
---@param pid any
---@return boolean
function info.isStreamDeck(pid)
    return pidToKind[pid] ~= nil
end

---@class KindInfo A way to query all kinds of information about the stream decks
---@field kind string
local kindInfo = {}
kindInfo.__index = kindInfo

---Gets the information based on kind string
---@param kind any
---@return KindInfo?
function info.fromKind(kind)
    if not kindToPID[kind] then
        return nil
    end

    local obj = { kind = kind }
    setmetatable(obj, kindInfo)
    return obj
end

---Gets the information based on Product ID
---@param pid number
---@return KindInfo?
function info.fromPID(pid)
    local kind = pidToKind[pid]

    if not kind then
        return nil
    end

    local obj = { kind = kind }
    setmetatable(obj, kindInfo)
    return obj
end

---Returns Product ID of the device kind
---@return integer
function kindInfo:getPID()
    return kindToPID[self.kind]
end

local function anyMatch(matchee, ...)
    for _, v in pairs({...}) do
        if matchee == v then
            return true
        end
    end
    return false
end

---Returns amount of keys the device has
---@return integer
function kindInfo:getKeyCount()
    if anyMatch(self.kind, ORIGINAL, ORIGINAL_V2, MK2, MK2_SCISSOR) then
        return 15
    elseif anyMatch(self.kind, MINI, MINI_MK2) then
        return 6
    elseif anyMatch(self.kind, XL, XL_V2) then
        return 32
    elseif self.kind == PEDAL then
        return 3
    elseif anyMatch(self.kind, NEO, PLUS) then
        return 8
    end

    return 0
end

---Returns amount of key rows the device has
---@return integer
function kindInfo:getRowCount()
    if anyMatch(self.kind, ORIGINAL, ORIGINAL_V2, MK2, MK2_SCISSOR) then
        return 3
    elseif anyMatch(self.kind, MINI, MINI_MK2) then
        return 2
    elseif anyMatch(self.kind, XL, XL_V2) then
        return 4
    elseif self.kind == PEDAL then
        return 1
    elseif anyMatch(self.kind, NEO, PLUS) then
        return 2
    end

    return 0
end

---Returns amount of key columns the device has
---@return integer
function kindInfo:getColumnCount()
    if anyMatch(self.kind, ORIGINAL, ORIGINAL_V2, MK2, MK2_SCISSOR) then
        return 5
    elseif anyMatch(self.kind, MINI, MINI_MK2) then
        return 3
    elseif anyMatch(self.kind, XL, XL_V2) then
        return 8
    elseif self.kind == PEDAL then
        return 3
    elseif anyMatch(self.kind, NEO, PLUS) then
        return 4
    end

    return 0
end

---Returns amount of encoders the device has
---@return integer
function kindInfo:getEncoderCount()
    if self.kind == PLUS then
        return 4
    end

    return 0
end

---Returns amount of touchpoints the device has
---@return integer
function kindInfo:getTouchpointCount()
    if self.kind == NEO then
        return 2
    end

    return 0
end

---Returns size of the screen if it has one
---@return integer? x
---@return integer? y
function kindInfo:getLCDStripSize()
    if self.kind == PLUS then
        return 800, 100
    elseif self.kind == NEO then
        return 248, 58
    end
end

---Returns if the device has a screen of any kind
---@return boolean
function kindInfo:isVisual()
    return self.kind ~= PEDAL
end

---@enum ImageKind Image type that the device expects
local imageKind = {
    none = 1,
    bmp = 2,
    jpeg = 3
}
info.imageKind = imageKind

---@enum ImageRotation Required rotation to put the image upright on the device
local imageRotation = {
    rot0 = 1,
    rot90 = 2,
    rot180 = 3,
    rot270 = 4
}
info.imageRotation = imageRotation

---@enum ImageMirror Required image mirrors to get image to display correctly
local imageMirror = {
    none = 1,
    x = 2,
    y = 3,
    both = 4
}
info.imageMirror = imageMirror

---@class ImageFormat Represents the requirements for what image has to
---@field kind ImageKind
---@field size number[]
---@field rotation ImageRotation
---@field mirror ImageMirror
local imgFormat = {}

---Returns key image format for the device
---@return ImageFormat
function kindInfo:getImageFormat()
    if self.kind == ORIGINAL then
        return {
            kind = imageKind.bmp,
            size = { 72, 72 },
            rotation = imageRotation.rot0,
            mirror = imageMirror.both
        }
    elseif anyMatch(self.kind, ORIGINAL_V2, MK2, MK2_SCISSOR) then
        return {
            kind = imageKind.jpeg,
            size = { 72, 72 },
            rotation = imageRotation.rot0,
            mirror = imageMirror.both
        }
    elseif anyMatch(self.kind, MINI, MINI_MK2) then
        return {
            kind = imageKind.bmp,
            size = { 80, 80 },
            rotation = imageRotation.rot90,
            mirror = imageMirror.x
        }
    elseif anyMatch(self.kind, NEO, XL, XL_V2) then
        return {
            kind = imageKind.jpeg,
            size = { 96, 96 },
            rotation = imageRotation.rot0,
            mirror = imageMirror.both
        }
    elseif self.kind == PLUS then
        return {
            kind = imageKind.jpeg,
            size = { 120, 120 },
            rotation = imageRotation.rot0,
            mirror = imageMirror.none,
        }
    end

    return {
        kind = imageKind.none,
        size = { 0, 0 },
        rotation = imageRotation.rot0,
        mirror = imageMirror.none
    }
end

---Returns LCD image format of the device
---@return ImageFormat?
function kindInfo:getLCDImageFormat()
    if self.kind == NEO then
        return {
            kind = imageKind.jpeg,
            size = { 248, 58 },
            rotation = imageRotation.rot180,
            mirror = imageMirror.none
        }
    elseif self.kind == PLUS then
        return {
            kind = imageKind.jpeg,
            size = { 800, 100 },
            rotation = imageRotation.rot0,
            mirror = imageMirror.none
        }
    end

    return nil
end

