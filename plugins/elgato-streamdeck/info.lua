---Returns blank image payload for the device
---@return number[]
function kindInfo:getBlankImage()
    if anyMatch(self.kind, ORIGINAL, MINI, MINI_MK2) then
        local data = buf( -- Bitmap Picture Header
            0x42, 0x4d, 0xf6, 0x3c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x36, 0x00, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00,
            0x48, 0x00, 0x00, 0x00, 0x48, 0x00, 0x00, 0x00, 0x01, 0x00, 0x18, 0x00,
            0x00, 0x00, 0x00, 0x00, 0xc0, 0x3c, 0x00, 0x00, 0xc4, 0x0e, 0x00, 0x00, 0xc4, 0x0e, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00
        )

        local size = self:getImageFormat().size

        return data:padRight(size[0] * size[1] * 3)
    elseif anyMatch(self.kind, ORIGINAL_V2, MK2, MK2_SCISSOR) then
        return originalBlankImage
    elseif anyMatch(self.kind, NEO, XL, XL_V2) then
        return neoBlankImage
    elseif self.kind == PLUS then
        return plusBlankImage
    end

    return {}
end

---Returns device layout based on kind
---@return DeviceLayout
function kindInfo:getLayout()
    local inputs = {}
    local outputs = {}

    local columns = self:getColumnCount()
    local rows = self:getRowCount()
    local gotScreen = self:isVisual()
    local format = self:getImageFormat()

    for y = 1, rows do
        for x = 1, columns do
            table.insert(inputs, {
                position_size = {
                    { (x - 1) * 10, (y - 1) * 10 },
                    { 9,            9 }
                },
                icon = "Button",
                events = {
                    common.buttonEvent
                }
            })

            if gotScreen then
                table.insert(outputs, {
                    attached_to_input = #inputs,
                    capabilities = {
                        { Display = format.size }
                    }
                })
            end
        end
    end

    if self.kind == info.PLUS then
        local w, h = self:getLCDStripSize()

        table.insert(inputs, {
            position_size = {
                { 0,                rows * 10 },
                { columns * 10 - 1, 10 }
            },
            icon = "TouchScreen",
            events = {
                common.touchScreenPressEvent,
                common.touchScreenLongPressEvent,
                common.touchScreenSwipeEvent
            }
        })

        table.insert(outputs, {
            attached_to_input = #inputs,
            capabilities = {
                { Display = { w, h } }
            }
        })

        for i = 1, self:getEncoderCount() do
            table.insert(inputs, {
                position_size = {
                    { (i - 1) * 10, rows * 10 + 10 },
                    { 9,            9 }
                },
                icon = "Encoder",
                events = {
                    common.buttonEvent,
                    common.encoderEvent
                }
            })
        end
    elseif self.kind == info.NEO then
        for i = 1, self:getTouchpointCount() do
            table.insert(inputs, {
                position_size = {
                    { (i - 1) * 30 + 2, 24 },
                    { 5,                5 }
                },
                icon = "Sensor",
                events = {
                    common.buttonEvent
                }
            })

            table.insert(outputs, {
                position_size = {
                    { (i - 1) * 30 + 1, 20 },
                    { 7,                3 }
                },
                attached_to_input = #inputs,
                capabilities = {
                    "RGBLight"
                }
            })
        end

        local w, h = self:getLCDStripSize()

        table.insert(outputs, {
            position_size = {
                { 10, 20 },
                { 19, 9 }
            },
            capabilities = {
                { Display = { w, h } }
            }
        })
    end

    return {
        name = self.kind,
        inputs = inputs,
        outputs = outputs
    }
end

